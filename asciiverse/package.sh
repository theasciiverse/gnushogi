#!/bin/sh
# Builds GNU Shogi with the Asciiverse changes (-DAV_PATHS, see PATCHES.md)
# and packs dist/gnushogi-<target>.tar.gz for av: the program at the top,
# the opening book (gnushogi.tbk) beside it, with COPYING, README, NEWS,
# the manual page and PATCHES.md. Leaves the program at out/gnushogi/gnushogi
# for the system packages, which put the book in /usr/share/gnushogi, the
# folder compiled in (--libdir=/usr/share).
#
#   asciiverse/package.sh x86_64-unknown-linux-musl
#
# CC, CFLAGS, LDFLAGS and LIBS go to configure as usual.
set -eu
cd "$(dirname "$0")/.."
target="$1"
autoreconf -f -i
rm -rf out && mkdir out
(
  cd out
  ../configure --prefix=/usr --libdir=/usr/share --with-curses
  # the opening patterns are generated by a helper program, one at a time
  make -C gnushogi gnushogi_bootstrap
  make -C gnushogi CPPFLAGS=-DAV_PATHS gnushogi
)
stage=stage/gnushogi
rm -rf "$stage" && mkdir -p "$stage" dist
cp out/gnushogi/gnushogi misc/gnushogi.tbk COPYING README NEWS PATCHES.md doc/gnushogi.6 "$stage/"
tar -czf "dist/gnushogi-$target.tar.gz" -C "$stage" .
ls dist
